#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const REPO = path.resolve(ROOT, '..', '..');
const SCHEMA_PATH = path.join(ROOT, 'codegen', 'pulsetrackr-contract.schema.json');
const OUT = path.join(REPO, 'docs', 'api', 'contract.md');

const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
const definitions = schema.definitions || {};
const exported = Object.entries(schema.properties || {})
  .map(([name, value]) => [name, refName(value)])
  .filter(([, ref]) => ref && definitions[ref]);

const lines = [
  '# PulseTrackr Contract API',
  '',
  '<!-- Generated by packages/contract/codegen/generate-api-docs.cjs. Do not edit by hand. -->',
  '',
  'This document is generated from `@pulsetrackr/contract` Zod schemas via JSON Schema. It covers callable payload/read-model shapes shared by iOS and Firebase Functions.',
  '',
  '## Schemas',
  '',
];

for (const [exportName, definitionName] of exported) {
  const definition = definitions[definitionName];
  lines.push(`### ${exportName}`);
  lines.push('');
  lines.push(`Definition: \`${definitionName}\``);
  lines.push('');
  lines.push('| Field | Type | Required | Description |');
  lines.push('| --- | --- | --- | --- |');
  const required = new Set(definition.required || []);
  for (const [field, property] of Object.entries(definition.properties || {})) {
    lines.push(`| \`${field}\` | ${typeLabel(property)} | ${required.has(field) ? 'yes' : 'no'} | ${description(property)} |`);
  }
  if (!Object.keys(definition.properties || {}).length) {
    lines.push('| _(none)_ |  |  |  |');
  }
  lines.push('');
}

lines.push('## Operational Notes');
lines.push('');
lines.push('- Incident submissions require server-validated coordinates; public coordinates are revealed only through the H3 k-anonymity policy.');
lines.push('- SOS exact location/trail disclosure is backend-only and audited; clients never receive private Firestore collection access.');
lines.push('- Firebase callable names are exported from `functions/src/index.js`; deploy with the `pulsetrackr-sos` functions codebase.');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`✓ API docs: ${path.relative(REPO, OUT)}`);

function refName(value) {
  const ref = value && value.$ref;
  return ref ? ref.split('/').at(-1) : null;
}

function typeLabel(property) {
  if (!property) return '`unknown`';
  if (property.$ref) return `\`${refName(property)}\``;
  if (property.anyOf) return property.anyOf.map(typeLabel).join(' or ');
  if (property.allOf) return property.allOf.map(typeLabel).join(' + ');
  if (property.enum) return property.enum.map((value) => `\`${value}\``).join(', ');
  if (property.type === 'array') return `array<${typeLabel(property.items)}>`;
  if (property.type === 'object') return '`object`';
  if (Array.isArray(property.type)) return property.type.map((value) => `\`${value}\``).join(' or ');
  return property.type ? `\`${property.type}\`` : '`unknown`';
}

function description(property) {
  const parts = [];
  if (property.description) parts.push(property.description.replace(/\n/g, ' '));
  if (property.format) parts.push(`format: ${property.format}`);
  if (property.minimum !== undefined) parts.push(`min: ${property.minimum}`);
  if (property.maximum !== undefined) parts.push(`max: ${property.maximum}`);
  if (property.maxLength !== undefined) parts.push(`max length: ${property.maxLength}`);
  if (property.pattern) parts.push(`pattern: \`${property.pattern}\``);
  return parts.join('; ').replace(/\|/g, '\\|');
}

